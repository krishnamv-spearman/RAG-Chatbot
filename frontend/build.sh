#!/bin/sh
# Vercel build for the static frontend (no npm, no bundler).
#   1. copy the site into dist/
#   2. write dist/js/config.js from API_BASE_URL (the Render backend's public URL)
#
# Local check:  API_BASE_URL=https://fund-facts-api.onrender.com sh build.sh
set -eu
cd "$(dirname "$0")"

API_BASE_URL="${API_BASE_URL:-}"
API_BASE_URL="${API_BASE_URL%/}"

# On Vercel the backend URL is required: without it the UI would call itself.
if [ -n "${VERCEL_ENV:-}" ] && [ -z "$API_BASE_URL" ]; then
  echo "build.sh: API_BASE_URL is not set (Vercel -> Project -> Settings -> Environment Variables)" >&2
  exit 1
fi
case "$API_BASE_URL" in
  ""|https://*|http://localhost*|http://127.0.0.1*) ;;
  *) echo "build.sh: API_BASE_URL must start with https:// (got '$API_BASE_URL')" >&2; exit 1 ;;
esac
# Keep the generated JavaScript string safe: plain URL characters only.
if printf '%s' "$API_BASE_URL" | grep -q '[^A-Za-z0-9._:/-]'; then
  echo "build.sh: API_BASE_URL contains invalid characters" >&2
  exit 1
fi

rm -rf dist
mkdir -p dist
cp -R index.html css js dist/
printf '// Generated by build.sh at %s\nwindow.FUND_FACTS_CONFIG = { apiBase: "%s" };\n' \
  "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$API_BASE_URL" > dist/js/config.js

for f in index.html css/app.css js/app.js js/api.js js/config.js js/icons.js js/pii.js; do
  [ -f "dist/$f" ] || { echo "build.sh: missing dist/$f" >&2; exit 1; }
done
grep -q 'src="/js/config.js"' dist/index.html || { echo "build.sh: index.html doesn't load config.js" >&2; exit 1; }
echo "build.sh: built dist/ (apiBase='${API_BASE_URL:-same origin}')"
